// Helper: get display text for a German dropdown value
export const getDisplayValue = (
  germanValue: string,
  translationMap: Record<string, string>,
  lang: Lang
): string => {
  if (lang === "DE" || !germanValue) return germanValue;
  return translationMap[germanValue] ?? germanValue;
};

// Helper: get display options for dropdowns (returns {value: germanValue, label: displayText})
export const getDropdownOptions = (
  germanOptions: string[],
  translationMap: Record<string, string>,
  lang: Lang
): { value: string; label: string }[] => {
  return germanOptions.map(opt => ({
    value: opt, // always German for storage
    label: lang === "EN" ? (translationMap[opt] ?? opt) : opt,
  }));
};
